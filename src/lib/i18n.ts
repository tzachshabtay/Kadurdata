export function metricName(code: string, fallback: string, language: Language) {
  if (language === "en") return fallback;
  const sourceCode = code.replace(/::(paired|per90)$/, "");
  return hebrewMetricNames[sourceCode] ?? fallback;
}

export function metricGroupName(code: string, fallback: string, language: Language) {
  return language === "he" ? hebrewMetricGroups[code] ?? metricName(code, fallback, language) : fallback;
}

export function per90Name(name: string, language: Language) {
  return language === "he" ? `${name} (ל-90 דקות)` : `${name} (90 min)`;
}

export function positionName(code: string, fallback: string, language: Language) {
  return language === "he" ? hebrewPositionLabels[code] ?? fallback : fallback;
}

export function categoryName(category: string, language: Language) {
  return language === "he" ? hebrewCategoryLabels[category] ?? category : category;
}

export function ratioPartName(code: string | null | undefined, language: Language) {
  if (language === "en") return null;
  if (!code) return "ערך";
  if (code.endsWith("_completed")) return "מדויקות";
  if (code.endsWith("_attempted")) return "ניסיונות";
  if (code.endsWith("_won")) return "מוצלחים";
  if (code.startsWith("successful_")) return "מוצלחים";
  return metricName(code, code, language);
}

